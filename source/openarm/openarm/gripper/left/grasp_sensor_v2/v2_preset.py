#
#   D1  **stage 1 안이 고원이다.** 값 = `r_lift = r_close × move_up` 에 목표 거리가
#       **없다** ⇒ ∂r/∂dist = 0. 정책은 문턱을 우연히 넘기 전까지 목표 방향 신호를
#       못 받는다. 이것이 시드 의존의 기계적 원인이다 — stage 2 문턱은 컵–목표
#       **150~161 mm** 인데 붕괴 후 실측 `cupd` 는 **146 · 160 · 170 mm** 로 세 판 모두
#       그 고원에 주차했다.
#   D2  **리프트 램프가 요구 z 의 20% 만 덮는다.** `LIFT_RAMP_SPAN` = 34 mm 인데
#       스폰→목표 z 는 **158 mm**(이송 거리 167 mm 의 94.6%).
#   D3  **계단 최상단이 도달 불가.** `r_settle` = 네 인자 곱이라 실측 최대 0.0106,
#       대부분 정확히 0 — 4 단 계단의 4 층이 학습 신호로 존재한 적이 없다.
#
# ★결정적 증거: 총보상은 유지된 채(R1-A 68.62 → 68.07, −0.8%) `atgoal` 만
#   0.0333 → 0.0000. 정책은 실패한 게 아니라 **이송하지 않고 같은 보상을 얻는 경로**를
#   찾았다.
#
# 재구성의 세 원칙(계약 테스트가 강제한다):
#   ① 연속 — 문턱에서 v_k → 1 이고 v_{k+1} → 0
#   ② 단조 — 각 단계 안에서 목표로 갈수록 v_k 증가
#   ③ 고원 없음 — 각 단계 안 어디서도 ∂r/∂(진행) ≠ 0
#
#   v_0 = r_grasp                                 ★불변(grasp/lift 는 잘 된다)
#   v_1 = clamp(r_transport / STAGE_THRESHOLD)    ★신 — dist 가 들어와 D1·D2 동시 해소
#   v_2 = r_close · P_dist · P_still · P_upright  ★신 — smoothstep 3 곱
#   v_3 = r_close · smoothstep(dist; ε → 0)       ★신 — 문턱에서 0 이라 연속
#
# ★v_1 이 리프트 램프를 **안 건드리고** D2 를 고친다: r_lift·D(dist)/0.1 이므로 램프가
#   40 mm 에서 포화해도 D(dist) 가 계속 위로 끌어올린다. 램프 상수를 늘리는 것보다
#   회귀 위험이 작다(reward-audit Check 4).
# ★부수 효과: r_lift = 0.885 로 stage 1 에 머물려면 dist ≥ 161 mm 여야 하는데 스폰이
#   167 mm 다. 즉 컵을 6 mm 만 목표 쪽으로 옮겨도 승급 — **stage 1 정체가 구조적으로
#   불가능해진다.**

