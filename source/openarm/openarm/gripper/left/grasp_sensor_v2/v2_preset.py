# ★★08.29 라운드 3 — 계단을 **연속·단조**로 재구성한다
# ---------------------------------------------------------------------------
# 사용자 판정: "시드에 따라 태스크 성공이 갈리면 잘못된 보상 함수 설계다. 양상은
