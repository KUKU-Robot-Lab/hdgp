# ---------------------------------------------------------------------------
# smoothstep 밴드 — (far, near). far 에서 0 · near 에서 1 · 사이는 3t²−2t³
# ---------------------------------------------------------------------------
# ★자매 트랙(`agnostic/grasp_sensor`)의 `succ_soft = s_h·s_c·s_o·s_t·s_d·s_v` 와 같은
#   패턴이다. 그쪽은 이송에 성공했고, 우리가 계단으로 백지 재설계하면서 버린 것이
#   바로 이 "조건마다 부드러운 진행도, 곱으로 합성" 구조였다.
#
# `P_dist` far 를 0.16 으로 잡는 근거: stage 2 진입 문턱이 r_lift 0.60~0.885 에서
