# Lee 의 거리 shaping D(a, b, s, τ) — 스케일에 **의미**를 준다
# ---------------------------------------------------------------------------
#   D = 1                                   if ‖a−b‖ < τ
#       1 − tanh²(‖a−b‖ · atanh(√0.95)/s)   otherwise
#   ⇒ `s` 는 **보상이 0.05 까지 떨어지는 거리**다. `std` 를 감으로 고르던 v1 과 달리
#     실측 스케일에서 곧장 유도할 수 있다.
#   v1 이력: coarse std 0.3→0.15 기각(t63) · fine std 0.05→0.12 역행(t64).
#   두 번 다 "이 std 가 무엇을 뜻하는가"가 정의돼 있지 않아서 생긴 시행착오였다.
D_SHAPE_K = math.atanh(math.sqrt(0.95))      # 2.18459…

