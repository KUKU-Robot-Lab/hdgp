#   지금까지는 **정책이 그 선행량을 스스로 학습**하고 있었다. 그만큼의 표현력과 학습량이
#   목표 정확도에서 빠져나간다(fab_test7 컵–목표 80 mm).
#
#   → PD 목표를 `fabric_q + (fabric_q − q_actual)` 로 민다. 정상상태에서 PD 토크는
#     τ = kp·(목표 − q) 이므로, 관측된 처짐만큼 목표를 더 밀면 그 토크가 중력을 상쇄해
#     q → fabric_q 가 된다. **관절공간이라 프레임 정합 문제가 없다.**
#   ⚠ 상한은 `ARM_IK_MAX_TRACKING_ERROR`(= effort 한계 / 강성)를 그대로 쓴다. 그 이상
#     밀어봐야 토크가 포화해 windup 만 쌓인다(IK 트랙에서 실측으로 확인된 값).
#   ⚠ 순간 오차를 그대로 쓰면 **가속 구간의 속도 지연까지** 보상해 팔이 과격해진다.
#     저역통과로 준정적 성분만 남긴다.
#   ★★식은 **적분기**여야 한다. 저역통과(순간 오차를 따라가기)로 짰다가 실측에서 처짐이
#     정확히 절반만 줄었다(40.9 → 22.3 mm · 24.3 → 12.6 mrad). 우연이 아니라 대수적 귀결이다:
